// Unknown characters draw as a hollow box
const MISSING = '#####|#...#|#...#|#...#|#...#|#...#|#####|.....';

function expand(design) {
  const rows = design.split('|').map((row) =>
    [...row].reduce((byte, pixel, i) => (pixel === '#' ? byte | (0x40 >> i) : byte), 0));
  return Object.freeze(rows.flatMap((row) => [row, row]));
}

const GLYPHS = new Map(Object.entries(DESIGNS).map(([ch, design]) => [ch, expand(design)]));
const MISSING_GLYPH = expand(MISSING);

// The 16 row bytes of a character
export function glyph(ch) {
  return GLYPHS.get(ch) || MISSING_GLYPH;
}

// A character's rows as text, '*' for a pixel, for showing the font in the explanation
export function glyphPicture(ch) {
  return glyph(ch).map((row) =>
    Array.from({ length: GLYPH_WIDTH }, (_, bit) => (row & (0x80 >> bit) ? '*' : '.')).join(''));
}
